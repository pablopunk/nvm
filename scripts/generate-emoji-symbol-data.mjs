import fs from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';

const EMOJI_DATA_URL =
  'https://raw.githubusercontent.com/muan/unicode-emoji-json/v0.9.0/data-by-emoji.json';
const EMOJI_KEYWORDS_URL =
  'https://raw.githubusercontent.com/muan/emojilib/v4.0.3/dist/emoji-en-US.json';
const UNICODE_DATA_URL =
  'https://www.unicode.org/Public/17.0.0/ucd/UnicodeData.txt';
const EMOJI_TEST_URL =
  'https://www.unicode.org/Public/17.0.0/emoji/emoji-test.txt';
const OUTPUT_PATH = path.join(
  process.cwd(),
  'src/electron/extensions/emoji-symbol-data.ts',
);

const INCLUDED_SYMBOL_CATEGORIES = new Set([
  'Pc',
  'Pd',
  'Pe',
  'Pf',
  'Pi',
  'Po',
  'Ps',
  'Sc',
  'Sk',
  'Sm',
  'So',
]);
const SKIPPED_SYMBOL_RANGES = [[0x1f000, 0x1fbff]];
const INCLUDED_SYMBOL_RANGES = [
  [0x00a0, 0x00ff],
  [0x2000, 0x22ff],
  [0x2300, 0x25ff],
  [0x2600, 0x27ff],
  [0x2b00, 0x2bff],
  [0x3000, 0x303f],
  [0x20a0, 0x20cf],
];

function symbolGroup(codePoint, category) {
  if (category === 'Sc') return 'Currency';
  if (codePoint >= 0x2190 && codePoint <= 0x21ff) return 'Arrows';
  if (category === 'Sm') return 'Math';
  if (category.startsWith('P')) return 'Punctuation';
  if (codePoint >= 0x25a0 && codePoint <= 0x25ff) return 'Shapes';
  if (codePoint >= 0x2500 && codePoint <= 0x257f) return 'Drawing';
  if (codePoint >= 0x2460 && codePoint <= 0x24ff) return 'Enclosed';
  if (codePoint >= 0x2000 && codePoint <= 0x206f) return 'Punctuation';
  if (codePoint >= 0x3000 && codePoint <= 0x303f) return 'Punctuation';
  return 'Technical';
}

function includesCodePoint(ranges, codePoint) {
  return ranges.some(([start, end]) => codePoint >= start && codePoint <= end);
}

function symbolRecords(unicodeData) {
  return unicodeData
    .trim()
    .split('\n')
    .map((line) => line.split(';'))
    .filter((fields) => INCLUDED_SYMBOL_CATEGORIES.has(fields[2]))
    .map((fields) => {
      const codePoint = Number.parseInt(fields[0], 16);
      const name = fields[1].toLowerCase();
      if (
        !Number.isFinite(codePoint) ||
        name.startsWith('<') ||
        !includesCodePoint(INCLUDED_SYMBOL_RANGES, codePoint) ||
        includesCodePoint(SKIPPED_SYMBOL_RANGES, codePoint)
      )
        return null;
      return [
        String.fromCodePoint(codePoint),
        name,
        symbolGroup(codePoint, fields[2]),
      ];
    })
    .filter(Boolean);
}

function emojiRecords(emojiData, keywords) {
  return Object.entries(emojiData).map(([glyph, metadata]) => [
    glyph,
    metadata.name,
    metadata.group,
    Array.from(
      new Set([metadata.slug, ...(keywords[glyph] || [])].filter(Boolean)),
    ),
    metadata.skin_tone_support === true ? 1 : 0,
  ]);
}

function skinToneVariants(emojiTest) {
  const variants = new Map();
  for (const line of emojiTest.split('\n')) {
    const match = line.match(/^([0-9A-F ]+)\s*; fully-qualified\s+#\s+(\S+)/);
    if (!match) continue;
    const toneMatches = Array.from(match[1].matchAll(/1F3F([B-F])/g));
    if (!toneMatches.length) continue;
    if (toneMatches.some((toneMatch) => toneMatch[1] !== toneMatches[0][1]))
      continue;
    const tone = Number.parseInt(toneMatches[0][1], 16) - 10;
    const baseCodePoints = match[1]
      .trim()
      .split(/\s+/)
      .filter((codePoint) => !/^1F3F[B-F]$/.test(codePoint));
    const baseGlyph = String.fromCodePoint(
      ...baseCodePoints.map((codePoint) => Number.parseInt(codePoint, 16)),
    );
    const baseVariants = variants.get(baseGlyph) || ['', '', '', '', ''];
    baseVariants[tone - 1] = match[2];
    variants.set(baseGlyph, baseVariants);
  }
  return Array.from(variants.entries()).filter(([, values]) =>
    values.every(Boolean),
  );
}

function generatedModule(emojis, symbols, variants) {
  return `// Generated by scripts/generate-emoji-symbol-data.mjs from Unicode 17.0, unicode-emoji-json 0.9.0, and emojilib 4.0.3.\n// Unicode data is licensed under the Unicode License v3; package-derived data is MIT licensed.\n\nexport type EmojiRecord = readonly [\n  glyph: string,\n  name: string,\n  group: string,\n  keywords: readonly string[],\n  supportsSkinTone: 0 | 1,\n];\nexport type SymbolRecord = readonly [\n  glyph: string,\n  name: string,\n  group: string,\n];\nexport type SkinToneVariants = readonly [\n  light: string,\n  mediumLight: string,\n  medium: string,\n  mediumDark: string,\n  dark: string,\n];\n\n// biome-ignore format: Generated compact data intentionally stays on one line.\nexport const EMOJI_RECORDS: readonly EmojiRecord[] = ${JSON.stringify(emojis)};\n\n// biome-ignore format: Generated compact data intentionally stays on one line.\nexport const SYMBOL_RECORDS: readonly SymbolRecord[] = ${JSON.stringify(symbols)};\n\n// biome-ignore format: Generated compact data intentionally stays on one line.\nexport const SKIN_TONE_VARIANTS: Readonly<Record<string, SkinToneVariants>> = Object.fromEntries(${JSON.stringify(variants)});\n`;
}

async function fetchText(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${response.status} ${url}`);
  return response.text();
}

const [emojiDataText, emojiKeywordsText, unicodeData, emojiTest] =
  await Promise.all([
    fetchText(EMOJI_DATA_URL),
    fetchText(EMOJI_KEYWORDS_URL),
    fetchText(UNICODE_DATA_URL),
    fetchText(EMOJI_TEST_URL),
  ]);
const emojiData = JSON.parse(emojiDataText);
const moduleText = generatedModule(
  emojiRecords(emojiData, JSON.parse(emojiKeywordsText)),
  symbolRecords(unicodeData),
  skinToneVariants(emojiTest),
);
await fs.writeFile(OUTPUT_PATH, moduleText);
