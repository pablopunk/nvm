import assert from 'node:assert/strict';
import test from 'node:test';
import { createElectronClipboardApi } from './electron-clipboard';

type FakeClipboardOptions = {
  has?: (format: string) => Promise<boolean>;
  read?: () => Promise<unknown[]>;
};

function createFakes(
  clipboardItems: Array<{ types: string[]; value: unknown }>,
  options: FakeClipboardOptions = {},
) {
  const calls = { readImage: 0, createFromBuffer: 0 };
  const clipboard = {
    read:
      options.read ??
      (async () =>
        clipboardItems.map((entry) => ({
          types: entry.types,
          getType: async () => entry.value,
        }))),
    has: options.has ?? (async () => false),
    readImage: () => {
      calls.readImage += 1;
      return { isEmpty: () => false, toPNG: () => Buffer.from('native-image') };
    },
    readText: () => '',
    clear: () => {},
  };
  const nativeImage = {
    createFromBuffer: (buffer: Buffer) => {
      calls.createFromBuffer += 1;
      return {
        isEmpty: () => buffer.length === 0,
        toPNG: () => buffer,
      };
    },
    createEmpty: () => ({ isEmpty: () => true, toPNG: () => Buffer.from('') }),
  };
  const api = createElectronClipboardApi({
    clipboard: clipboard as any,
    nativeImage: nativeImage as any,
    ClipboardItem: class {
      constructor(
        _items: Record<string, string | Blob | { title: string; url: string }>,
      ) {}
      getType(
        type: 'electron application/bookmark',
      ): Promise<{ title: string; url: string }>;
      getType(type: string): Promise<Blob>;
      getType(type: string) {
        return Promise.resolve(
          type === 'electron application/bookmark'
            ? { title: '', url: '' }
            : new Blob(),
        );
      }
      types: string[] = [];
    },
  });
  return { api, calls };
}

test('readImage decodes explicit png clipboard items', async () => {
  const { api, calls } = createFakes([
    { types: ['image/png'], value: new Blob([Buffer.from('png-bytes')]) },
  ]);

  const image = await api.readImage();

  assert.equal(image.isEmpty(), false);
  assert.equal(calls.createFromBuffer, 1);
  assert.equal(calls.readImage, 0, 'native fallback should not be used');
});

test('readImage decodes non-png image clipboard items', async () => {
  const { api, calls } = createFakes([
    { types: ['image/tiff'], value: new Blob([Buffer.from('tiff-bytes')]) },
  ]);

  const image = await api.readImage();

  assert.equal(image.isEmpty(), false);
  assert.equal(calls.createFromBuffer, 1);
  assert.equal(calls.readImage, 0);
});

test('readImage returns an empty image for empty clipboards', async () => {
  const { api, calls } = createFakes([]);

  const image = await api.readImage();

  assert.equal(image.isEmpty(), true);
  assert.equal(calls.readImage, 0);
});

const CONCEALED_RAW_FORMAT =
  'electron application/osclipboard;format="org.nspasteboard.ConcealedType"';

test('hasFormat detects a marker stored under the raw clipboard format', async () => {
  const { api } = createFakes([
    { types: ['text/plain', CONCEALED_RAW_FORMAT], value: new Blob() },
  ]);

  assert.equal(await api.hasFormat('org.nspasteboard.ConcealedType'), true);
});

test('hasFormat detects a marker stored under the plain format', async () => {
  const { api } = createFakes([
    {
      types: ['text/plain', 'org.nspasteboard.TransientType'],
      value: new Blob(),
    },
  ]);

  assert.equal(await api.hasFormat('org.nspasteboard.TransientType'), true);
});

test('hasFormat trusts the native probe when item types do not list the format', async () => {
  const { api } = createFakes([{ types: ['text/plain'], value: new Blob() }], {
    has: async () => true,
  });

  assert.equal(await api.hasFormat('org.nspasteboard.AutoGeneratedType'), true);
});

test('hasFormat returns false for ordinary clipboard items', async () => {
  const { api } = createFakes([{ types: ['text/plain'], value: new Blob() }]);

  assert.equal(await api.hasFormat('org.nspasteboard.ConcealedType'), false);
});

test('hasFormat falls back to item types when the native probe throws', async () => {
  const { api } = createFakes(
    [{ types: ['text/plain', CONCEALED_RAW_FORMAT], value: new Blob() }],
    {
      has: async () => {
        throw new Error('unsupported format');
      },
    },
  );

  assert.equal(await api.hasFormat('org.nspasteboard.ConcealedType'), true);
});

test('hasFormat fails open to false when clipboard reads throw', async () => {
  const { api } = createFakes([], {
    read: async () => {
      throw new Error('pasteboard unavailable');
    },
  });

  assert.equal(await api.hasFormat('org.nspasteboard.ConcealedType'), false);
});
