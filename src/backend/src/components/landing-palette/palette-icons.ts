import {
  Activity,
  AppWindow,
  CircleStop,
  Clipboard,
  Download,
  FileCode,
  FileSearch,
  FileText,
  Folder,
  History,
  Image,
  Keyboard,
  Link,
  List,
  Lock,
  type LucideIcon,
  Mic,
  Moon,
  Palette,
  Power,
  RotateCcw,
  Search,
  Settings,
  SmilePlus,
  Sparkles,
  StickyNote,
  Terminal,
  Type,
  X,
  Zap,
} from 'lucide-react';

/** Lucide glyphs by the kebab-case names the desktop app uses. */
const ICONS: Record<string, LucideIcon> = {
  activity: Activity,
  'app-window': AppWindow,
  clipboard: Clipboard,
  download: Download,
  'file-code': FileCode,
  'file-search': FileSearch,
  'file-text': FileText,
  folder: Folder,
  history: History,
  image: Image,
  keyboard: Keyboard,
  link: Link,
  list: List,
  lock: Lock,
  mic: Mic,
  moon: Moon,
  palette: Palette,
  power: Power,
  'rotate-ccw': RotateCcw,
  search: Search,
  settings: Settings,
  'smile-plus': SmilePlus,
  sparkles: Sparkles,
  'sticky-note': StickyNote,
  'stop-circle': CircleStop,
  terminal: Terminal,
  type: Type,
  x: X,
  zap: Zap,
};

export function iconNamed(name: string | undefined): LucideIcon {
  return (name && ICONS[name]) || Sparkles;
}
