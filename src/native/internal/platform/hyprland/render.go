package hyprland

import (
	"fmt"
	"regexp"
	"slices"
	"strings"
)

// Bind is one shortcut: a canonical accelerator and the POSIX shell command it runs, such as the action command line.
type Bind struct {
	Accelerator string
	Command     string
}

// Appearance is the window appearance the module asks the compositor for.
type Appearance struct {
	// Undecorated removes the compositor's border, rounding, shadow and blur from the app's ordinary windows (not
	// from the palette, which is a layer surface).
	Undecorated bool
	// Classes are the app IDs the app's windows carry; at least one is needed for a window rule.
	Classes []string
}

// Desired is everything the module should hold.
type Desired struct {
	Binds      []Bind
	Appearance Appearance
}

// Skipped is a part of the desired state the module cannot hold, and why.
type Skipped struct {
	What   string
	Reason string
}

// moduleHeader opens every module; ownedModule recognizes it.
const moduleHeader = "Generated by Nevermind. Change these shortcuts and window rules in Nevermind (Command-K); edits here are replaced."

// Render writes the module for a format and version. Binds and rules it cannot write are returned as skipped, never
// guessed at. The output is deterministic, so an unchanged state renders to the same bytes.
func Render(f Format, v Version, d Desired) ([]byte, []Skipped) {
	support := SupportFor(v, f)
	comment := commentPrefix(f)
	var b strings.Builder
	fmt.Fprintf(&b, "%s %s\n%s Hyprland %s, %s format.\n", comment, moduleHeader, comment, v, f)
	var skipped []Skipped
	fmt.Fprintf(&b, "\n%s >>> shortcuts\n", comment)
	for _, bind := range sortedBinds(d.Binds) {
		line, err := renderBind(f, support, bind)
		if err != nil {
			skipped = append(skipped, Skipped{What: bind.Accelerator, Reason: err.Error()})
			continue
		}
		b.WriteString(line + "\n")
	}
	fmt.Fprintf(&b, "%s <<< shortcuts\n\n%s >>> appearance\n", comment, comment)
	if d.Appearance.Undecorated {
		line, err := renderUndecoratedRule(f, support, d.Appearance.Classes)
		if err != nil {
			skipped = append(skipped, Skipped{What: "window appearance", Reason: err.Error()})
		} else {
			b.WriteString(line + "\n")
		}
	}
	fmt.Fprintf(&b, "%s <<< appearance\n", comment)
	return []byte(b.String()), skipped
}

func commentPrefix(f Format) string {
	if f == FormatLua {
		return "--"
	}
	return "#"
}

func sortedBinds(binds []Bind) []Bind {
	out := slices.Clone(binds)
	slices.SortStableFunc(out, func(a, b Bind) int { return strings.Compare(a.Accelerator, b.Accelerator) })
	return out
}

func renderBind(f Format, support Support, bind Bind) (string, error) {
	if !support.Binds {
		return "", fmt.Errorf("this Hyprland version and config format take no generated shortcuts")
	}
	c, err := parseAccelerator(bind.Accelerator)
	if err != nil {
		return "", err
	}
	if bind.Command == "" || strings.ContainsAny(bind.Command, "\n\r\x00") {
		return "", fmt.Errorf("the command is empty or spans lines")
	}
	if f == FormatLua {
		keys := strings.Join(append(slices.Clone(c.mods), c.key), " + ")
		return fmt.Sprintf("hl.bind(%s, hl.dsp.exec_cmd(%s))", luaQuote(keys), luaQuote(bind.Command)), nil
	}
	// hyprlang reads # as a comment and expands $variables before the shell sees the command.
	if strings.ContainsAny(bind.Command, "#$") {
		return "", fmt.Errorf("the command has # or $, which hyprland.conf cannot carry")
	}
	return fmt.Sprintf("bind = %s, %s, exec, %s", strings.Join(c.mods, " "), c.key, bind.Command), nil
}

// The effects of an undecorated window, with their hyprlang and Lua values.
var undecoratedEffects = []struct{ name, conf, lua string }{
	{"border_size", "0", "0"},
	{"rounding", "0", "0"},
	{"no_shadow", "on", "true"},
	{"no_blur", "on", "true"},
	{"decorate", "off", "false"},
}

func renderUndecoratedRule(f Format, support Support, classes []string) (string, error) {
	if !support.WindowRules {
		return "", fmt.Errorf("window rules need Hyprland %s or later in this config format", windowRulesV3)
	}
	pattern, err := classPattern(classes)
	if err != nil {
		return "", err
	}
	var effects []string
	if f == FormatLua {
		for _, e := range undecoratedEffects {
			effects = append(effects, e.name+" = "+e.lua)
		}
		return fmt.Sprintf("hl.window_rule({ name = %s, match = { class = %s }, %s })",
			luaQuote("nevermind-undecorated"), luaQuote(pattern), strings.Join(effects, ", ")), nil
	}
	for _, e := range undecoratedEffects {
		effects = append(effects, e.name+" "+e.conf)
	}
	if strings.ContainsAny(pattern, "#$,") {
		return "", fmt.Errorf("the app ID has characters hyprland.conf cannot carry")
	}
	return fmt.Sprintf("windowrule = match:class %s, %s", pattern, strings.Join(effects, ", ")), nil
}

// classPattern matches exactly one of the app IDs. Hyprland matches rule patterns against the whole class, so the
// pattern carries no anchors: a $ anchor would read as a variable in hyprland.conf.
func classPattern(classes []string) (string, error) {
	var quoted []string
	for _, c := range classes {
		if c != "" && !slices.Contains(quoted, regexp.QuoteMeta(c)) {
			quoted = append(quoted, regexp.QuoteMeta(c))
		}
	}
	if len(quoted) == 0 {
		return "", fmt.Errorf("the app ID of Nevermind's windows is unknown")
	}
	return "(" + strings.Join(quoted, "|") + ")", nil
}

// luaQuote spells s as a Lua string literal. Bytes outside printable ASCII other than UTF-8 text are escaped in
// decimal, which every Lua version reads.
func luaQuote(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c == '\\' || c == '"':
			b.WriteByte('\\')
			b.WriteByte(c)
		case c < 0x20 || c == 0x7f:
			fmt.Fprintf(&b, "\\%03d", c)
		default:
			b.WriteByte(c)
		}
	}
	b.WriteByte('"')
	return b.String()
}

// ownedModule reports whether data is a module this package wrote.
func ownedModule(data []byte) bool {
	first, _, _ := strings.Cut(string(data), "\n")
	return strings.Contains(first, moduleHeader)
}
