package real

import "testing"

// TestConcealedMarkersAreRecognised: each marker a password manager advertises, in the raw names of its platform,
// marks the copy concealed. The X11 name is the KDE hint, matched case-insensitively.
func TestConcealedMarkersAreRecognised(t *testing.T) {
	concealed := [][]string{
		{"org.nspasteboard.ConcealedType"},
		{"org.nspasteboard.TransientType"},
		{"org.nspasteboard.AutoGeneratedType"},
		{"ExcludeClipboardContentFromMonitorProcessing"},
		{"x-kde-passwordManagerHint"},
		{"UTF8_STRING", "X-KDE-PASSWORDMANAGERHINT"},
	}
	for _, formats := range concealed {
		if !isConcealedClipboard(formats) {
			t.Errorf("%v is not concealed", formats)
		}
	}
	if isConcealedClipboard([]string{"UTF8_STRING", "text/html", "image/png"}) {
		t.Error("an ordinary copy is concealed")
	}
}
