const sampleSource = `// header comment
export type EmojiRecord = readonly [glyph: string];
export const EMOJI_RECORDS: readonly EmojiRecord[] = [["😀","grinning face","Smileys & Emotion",["smile","happy"],0],["👋","waving hand","People & Body",["hello","wave"],1]];
export const SYMBOL_RECORDS: readonly SymbolRecord[] = [["✓","check mark","Technical"],["∞","infinity","Math"]];
export const SKIN_TONE_VARIANTS: Readonly<Record<string, SkinToneVariants>> = Object.fromEntries([["👋",["👋🏻","👋🏼","👋🏽","👋🏾","👋🏿"]]]);
`

// repositoryDataPath is the TypeScript catalog relative to this test's package directory.
const repositoryDataPath = "../../../../../app/extensions/emoji-symbol-data.ts"

// checkedInPath is the generated file relative to this test's package directory.
const checkedInPath = "../catalog_data.go"

func TestGenerateIsDeterministic(t *testing.T) {
	first, err := generate([]byte(sampleSource))
	if err != nil {
		t.Fatalf("generate: %v", err)
	}
	second, err := generate([]byte(sampleSource))
	if err != nil {
		t.Fatalf("generate again: %v", err)
	}
	if !bytes.Equal(first, second) {
		t.Fatal("two runs over the same source produced different bytes")
	}
}

func TestGenerateEmitsGeneratedHeaderAndTables(t *testing.T) {
	out, err := generate([]byte(sampleSource))
	if err != nil {
		t.Fatalf("generate: %v", err)
	}
	text := string(out)
	for _, want := range []string{
		"// Code generated by gen from emoji-symbol-data.ts; DO NOT EDIT.",
		"package emoji",
		"const catalogText",
		"var stringOffsets = [...]uint32{",
		"var records = [...]record{",
		"{0, 1, 2, 0, 2, KindEmoji, false}",
		"var skinVariants = [...]skinVariant{",
	} {
		if !strings.Contains(text, want) {
			t.Errorf("generated file lacks %q", want)
		}
	}
}

func TestGenerateRejectsInvalidSources(t *testing.T) {
	tests := []struct {
		name   string
		mutate func(string) string
		want   string
	}{
		{
			name:   "unsupported escape",
			mutate: func(s string) string { return strings.Replace(s, "grinning face", `grinning \d face`, 1) },
			want:   "unsupported escape",
		},
		{
			name: "skin flag out of range",
			mutate: func(s string) string {
				return strings.Replace(s, `"People & Body",["hello","wave"],1]`, `"People & Body",["hello","wave"],2]`, 1)
			},
			want: "supportsSkinTone must be 0 or 1",
		},
		{
			name: "duplicate symbol",
			mutate: func(s string) string {
				return strings.Replace(s, `["∞","infinity","Math"]`, `["✓","check mark","Technical"]`, 1)
			},
			want: "duplicate KindSymbol",
		},
		{
			name:   "variant without modifier",
			mutate: func(s string) string { return strings.Replace(s, `"👋🏻","👋🏼"`, `"👋","👋🏼"`, 1) },
			want:   "lacks modifier",
		},
		{
			name:   "missing declaration",
			mutate: func(s string) string { return strings.Replace(s, "export const SYMBOL_RECORDS", "const SYMBOLS", 1) },
			want:   "declaration SYMBOL_RECORDS not found",
		},
		{
			name: "missing field",
			mutate: func(s string) string {
				return strings.Replace(s, `["✓","check mark","Technical"]`, `["✓","check mark"]`, 1)
			},
			want: "want 3 fields",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			_, err := generate([]byte(tt.mutate(sampleSource)))
			if err == nil || !strings.Contains(err.Error(), tt.want) {
				t.Fatalf("got error %v, want one containing %q", err, tt.want)
			}
		})
	}
}

func TestParserReadsEscapesCommentsAndWrappers(t *testing.T) {
	// The JavaScript under test spells its escapes with a doubled backslash here, so the Go source
	// stays literal: \u{1F469}, ‍ and \u{1F4BB} reach the parser as escapes, not characters.
	src := "export const LIST: T = /* block */ [ // line\n" +
		"\t[\"\\u{1F469}\\u200D\\u{1F4BB}\", \"a\\\\b\\\"c\", 'it\\'s', \"\\x41\\u0042\", 1,],\n" +
		"];"
	list, err := parseExportedArray(src, "LIST")
	if err != nil {
		t.Fatalf("parseExportedArray: %v", err)
	}
	row, ok := list[0].([]any)
	if !ok || len(row) != 5 {
		t.Fatalf("row = %#v", list[0])
	}
	woman := "👩" + string(rune(0x200D)) + "💻"
	want := []string{woman, `a\b"c`, "it's", "AB"}
	for index, expect := range want {
		if got := row[index].(string); got != expect {
			t.Errorf("field %d = %q, want %q", index, got, expect)
		}
	}
	if row[4].(int) != 1 {
		t.Errorf("number field = %v, want 1", row[4])
	}
}

func TestParserRejectsSurrogateAndUnterminatedInput(t *testing.T) {
	for _, src := range []string{
		`export const X = [["\uD83D"]];`,
		`export const X = [["open`,
		`export const X = [1 2];`,
	} {
		if _, err := parseExportedArray(src, "X"); err == nil {
			t.Errorf("parseExportedArray(%q) succeeded, want an error", src)
		}
	}
}

func TestGenerateMatchesCheckedInFile(t *testing.T) {
	source, err := os.ReadFile(repositoryDataPath)
	if err != nil {
		t.Fatalf("read the TypeScript catalog: %v", err)
	}
	want, err := generate(source)
	if err != nil {
		t.Fatalf("generate from repository source: %v", err)
	}
	got, err := os.ReadFile(filepath.Clean(checkedInPath))
	if err != nil {
		t.Fatalf("read checked-in catalog_data.go: %v", err)
	}
	if !bytes.Equal(got, want) {
		t.Fatal("catalog_data.go is stale: run go generate ./internal/features/emoji/...")
	}
}
