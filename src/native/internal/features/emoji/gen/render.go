package main

import (
	"bytes"
	"fmt"
	"go/format"
	"strconv"
	"strings"
)

const (
	textChunkBytes = 240
	offsetsPerLine = 32
	idsPerLine     = 24
)

// generate turns the TypeScript catalog source into the Go file contents. The result is gofmt-clean
// and a pure function of its input, which the determinism test relies on.
func generate(data []byte) ([]byte, error) {
	decoded, err := decodeSource(data)
	if err != nil {
		return nil, err
	}
	if err := validateSource(decoded); err != nil {
		return nil, err
	}
	tables, err := buildTables(decoded)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by gen from emoji-symbol-data.ts; DO NOT EDIT.\n\npackage emoji\n\n")
	writeText(&b, tables.strings)
	writeOffsets(&b, tables.strings)
	writeNumberList(&b, "categoryNames", "uint16", "group string ids in catalog order: emoji groups first, then symbol groups", idsPerLine, tables.categories)
	writeNumberList(&b, "keywordIDs", "uint16", "keyword string ids for every entry, indexed by record.keywordStart", idsPerLine, tables.keywordIDs)
	writeRecords(&b, tables.records)
	writeSkins(&b, tables.skins)
	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated code: %w", err)
	}
	return formatted, nil
}

// writeText emits catalogText as a chain of quoted chunks. Chunks break only between strings, so
// every quoted piece is whole UTF-8 and the offsets written by writeOffsets stay exact.
func writeText(b *bytes.Buffer, values []string) {
	b.WriteString("// catalogText holds every distinct catalog string back to back; stringOffsets locates them.\n")
	b.WriteString("const catalogText = \"\" +\n")
	var chunk strings.Builder
	for _, value := range values {
		if chunk.Len() > 0 && chunk.Len()+len(value) > textChunkBytes {
			writeChunk(b, chunk.String())
			chunk.Reset()
		}
		chunk.WriteString(value)
	}
	writeChunk(b, chunk.String())
	b.WriteString("\t\"\"\n\n")
}

func writeChunk(b *bytes.Buffer, chunk string) {
	if chunk == "" {
		return
	}
	fmt.Fprintf(b, "\t%s +\n", strconv.Quote(chunk))
}

func writeOffsets(b *bytes.Buffer, values []string) {
	offsets := make([]uint32, 0, len(values)+1)
	var total uint32
	for _, value := range values {
		offsets = append(offsets, total)
		total += uint32(len(value))
	}
	offsets = append(offsets, total)
	writeNumberList(b, "stringOffsets", "uint32", "byte offset of string i in catalogText; string i ends where string i+1 starts", offsetsPerLine, offsets)
}

func writeNumberList[T uint16 | uint32](b *bytes.Buffer, name, typ, doc string, perLine int, values []T) {
	fmt.Fprintf(b, "// %s holds %s.\nvar %s = [...]%s{\n", name, doc, name, typ)
	for start := 0; start < len(values); start += perLine {
		end := min(start+perLine, len(values))
		parts := make([]string, 0, end-start)
		for _, value := range values[start:end] {
			parts = append(parts, strconv.FormatUint(uint64(value), 10))
		}
		fmt.Fprintf(b, "\t%s,\n", strings.Join(parts, ", "))
	}
	b.WriteString("}\n\n")
}

func writeRecords(b *bytes.Buffer, rows []recordRow) {
	b.WriteString("// records lists every entry in catalog order. Fields: glyph, name, group, keywordStart, keywordCount, kind, skinTone.\n")
	b.WriteString("var records = [...]record{\n")
	for _, row := range rows {
		fmt.Fprintf(b, "\t{%d, %d, %d, %d, %d, %s, %t},\n", row.glyph, row.name, row.group, row.keywordStart, row.keywordCount, row.kindName, row.skinTone)
	}
	b.WriteString("}\n\n")
}

func writeSkins(b *bytes.Buffer, rows []skinRow) {
	b.WriteString("// skinVariants is the TypeScript SKIN_TONE_VARIANTS table, sorted by base glyph for binary search.\n")
	b.WriteString("var skinVariants = [...]skinVariant{\n")
	for _, row := range rows {
		fmt.Fprintf(b, "\t{%d, [5]uint16{%d, %d, %d, %d, %d}},\n", row.base, row.tones[0], row.tones[1], row.tones[2], row.tones[3], row.tones[4])
	}
	b.WriteString("}\n")
}
