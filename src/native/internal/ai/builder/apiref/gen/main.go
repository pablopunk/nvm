// Command gen writes the builder's generated API reference: go run ./apiref/gen -api ../../ext/api -out reference_gen.go.
// Run it from internal/ai/builder (the go:generate directive does) after an api change; a test fails until it does.
package main

import (
	"flag"
	"fmt"
	"os"
	"strconv"
	"strings"

	"github.com/pablopunk/nvm/native/internal/ai/builder/apiref"
)

const header = `// Code generated by apiref/gen from the api package; DO NOT EDIT.

package builder

// apiReference is the extension API reference the builder reads on demand. See apiref.Render.
var apiReference = `

func main() {
	apiDir := flag.String("api", "../../ext/api", "directory of the api package")
	out := flag.String("out", "reference_gen.go", "generated file to write")
	subset := flag.String("subset", "", "comma-separated Context accessors; writes only their terse reference instead of the builder's")
	pkg := flag.String("package", "codemode", "package of the subset file")
	name := flag.String("var", "apiSubset", "variable of the subset file")
	flag.Parse()
	if *subset != "" {
		if err := runSubset(*apiDir, *out, strings.Split(*subset, ","), *pkg, *name); err != nil {
			fmt.Fprintln(os.Stderr, "apiref:", err)
			os.Exit(1)
		}
		return
	}
	if err := run(*apiDir, *out); err != nil {
		fmt.Fprintln(os.Stderr, "apiref:", err)
		os.Exit(1)
	}
}

// compactHeader opens the file's second constant, the terse reference the builder preloads.
const compactHeader = `
// apiReferenceCompact is the terse extension API reference the builder preloads into every turn. See apiref.RenderCompact.
var apiReferenceCompact = `

func run(apiDir, out string) error {
	fsys := os.DirFS(apiDir)
	text, err := apiref.Render(fsys)
	if err != nil {
		return err
	}
	compact, err := apiref.RenderCompact(fsys)
	if err != nil {
		return err
	}
	return os.WriteFile(out, []byte(header+strconv.Quote(text)+"\n"+compactHeader+strconv.Quote(compact)+"\n"), 0o644)
}

// runSubset writes the terse reference of the listed accessors as one string variable of package pkg.
func runSubset(apiDir, out string, accessors []string, pkg, name string) error {
	text, err := apiref.RenderSubset(os.DirFS(apiDir), accessors)
	if err != nil {
		return err
	}
	source := fmt.Sprintf("// Code generated by apiref/gen from the api package; DO NOT EDIT.\n\npackage %s\n\n// %s is the terse API reference of the Context accessors %s. See apiref.RenderSubset.\nvar %s = %s\n",
		pkg, name, strings.Join(accessors, ", "), name, strconv.Quote(text))
	return os.WriteFile(out, []byte(source), 0o644)
}
