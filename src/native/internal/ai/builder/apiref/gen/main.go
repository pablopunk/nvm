// Command gen writes the builder's generated API reference: go run ./apiref/gen -api ../../ext/api -out reference_gen.go.
// Run it from internal/ai/builder (the go:generate directive does) after an api change; a test fails until it does.
package main

import (
	"flag"
	"fmt"
	"os"
	"strconv"

	"github.com/pablopunk/nvm/native/internal/ai/builder/apiref"
)

const header = `// Code generated by apiref/gen from the api package; DO NOT EDIT.

package builder

// apiReference is the extension API reference the builder gives the model. See apiref.Render.
var apiReference = `

func main() {
	apiDir := flag.String("api", "../../ext/api", "directory of the api package")
	out := flag.String("out", "reference_gen.go", "generated file to write")
	flag.Parse()
	if err := run(*apiDir, *out); err != nil {
		fmt.Fprintln(os.Stderr, "apiref:", err)
		os.Exit(1)
	}
}

func run(apiDir, out string) error {
	text, err := apiref.Render(os.DirFS(apiDir))
	if err != nil {
		return err
	}
	return os.WriteFile(out, []byte(header+strconv.Quote(text)+"\n"), 0o644)
}
