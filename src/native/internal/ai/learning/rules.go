package learning

import (
	"crypto/hmac"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"strings"
	"unicode"
	"unicode/utf8"

	"github.com/pablopunk/nvm/native/internal/store"
)

const maxRules = 200
const maxTombstones = 512

var ErrConflict = errors.New("learning: revision changed")
var ErrInvalid = errors.New("learning: invalid rule")

type Rule struct {
	ID          string `json:"id"`
	Kind        string `json:"kind"`
	Text        string `json:"text"`
	AppliesWhen string `json:"appliesWhen,omitempty"`
	Revision    uint64 `json:"revision"`
}
type Document struct {
	Revision   uint64   `json:"revision"`
	Rules      []Rule   `json:"rules"`
	Tombstones []string `json:"tombstones"`
}

type Rules struct {
	doc *store.Collection[Document]
	key []byte
}

// OpenRules loads committed state. key must be stable and private to this installation.
func OpenRules(doc *store.Collection[Document], key []byte) (*Rules, error) {
	if doc == nil || len(key) < 32 {
		return nil, errors.New("learning: persistent fingerprint key required")
	}
	if _, err := doc.Load(); err != nil {
		return nil, err
	}
	if doc.ReadOnly() {
		return nil, store.ErrReadOnly
	}
	return &Rules{doc: doc, key: append([]byte(nil), key...)}, nil
}
func (r *Rules) Snapshot() (Document, error) { return r.doc.Load() }

func validText(text string, required bool) bool {
	if !utf8.ValidString(text) || len(text) > 300 || (required && strings.TrimSpace(text) == "") || unsafeText.MatchString(text) {
		return false
	}
	for _, ch := range text {
		if unicode.IsControl(ch) && ch != '\n' {
			return false
		}
	}
	return true
}
func validRule(rule Rule) bool {
	return rule.ID != "" && (rule.Kind == "environment" || rule.Kind == "workflow" || rule.Kind == "preference") && validText(rule.Text, true) && validText(rule.AppliesWhen, false)
}
func (r *Rules) fingerprint(text string) string {
	h := hmac.New(sha256.New, r.key)
	_, _ = h.Write([]byte(strings.ToLower(strings.Join(strings.Fields(text), " "))))
	return hex.EncodeToString(h.Sum(nil))
}

// Edit replaces an existing rule only when both collection and rule revisions match.
func (r *Rules) Edit(expected uint64, updated Rule) error {
	updated.Text = strings.TrimSpace(updated.Text)
	updated.AppliesWhen = strings.TrimSpace(updated.AppliesWhen)
	if !validRule(updated) {
		return ErrInvalid
	}
	return r.doc.Commit(func(doc *Document) error {
		if doc.Revision != expected {
			return ErrConflict
		}
		for i, old := range doc.Rules {
			if old.ID == updated.ID {
				if old.Revision != updated.Revision {
					return ErrConflict
				}
				updated.Revision++
				doc.Rules[i] = updated
				doc.Revision++
				return nil
			}
		}
		return ErrConflict
	})
}

// Delete records a suppression fingerprint atomically with removal. The caller also invalidates
// pre-deletion in-memory traces before any later review is scheduled.
func (r *Rules) Delete(expected uint64, id string, revision uint64) error {
	return r.doc.Commit(func(doc *Document) error {
		if doc.Revision != expected {
			return ErrConflict
		}
		for i, old := range doc.Rules {
			if old.ID == id {
				if old.Revision != revision {
					return ErrConflict
				}
				if len(doc.Tombstones) >= maxTombstones {
					return errors.New("learning: deletion protection is full")
				}
				doc.Tombstones = append(doc.Tombstones, r.fingerprint(old.Text))
				doc.Rules = append(doc.Rules[:i], doc.Rules[i+1:]...)
				doc.Revision++
				return nil
			}
		}
		return ErrConflict
	})
}

// ApplyAdds commits validated model proposals only against the reviewed collection revision.
// IDs are host-generated by the caller. The job must also guard its trace generation and watermark.
func (r *Rules) ApplyAdds(expected uint64, additions []Rule) error {
	if len(additions) > 20 {
		return ErrInvalid
	}
	for i := range additions {
		additions[i].Text = strings.TrimSpace(additions[i].Text)
		additions[i].AppliesWhen = strings.TrimSpace(additions[i].AppliesWhen)
		if !validRule(additions[i]) {
			return ErrInvalid
		}
	}
	return r.doc.Commit(func(doc *Document) error {
		if doc.Revision != expected {
			return ErrConflict
		}
		if len(doc.Rules)+len(additions) > maxRules {
			return errors.New("learning: rule limit reached")
		}
		if len(doc.Tombstones) >= maxTombstones && len(additions) > 0 {
			return errors.New("learning: deletion protection is full")
		}
		ids := map[string]bool{}
		for _, rule := range doc.Rules {
			ids[rule.ID] = true
		}
		for _, rule := range additions {
			if ids[rule.ID] {
				return ErrInvalid
			}
			ids[rule.ID] = true
			for _, tomb := range doc.Tombstones {
				if tomb == r.fingerprint(rule.Text) {
					return fmt.Errorf("%w: previously deleted", ErrInvalid)
				}
			}
			rule.Revision = 1
			doc.Rules = append(doc.Rules, rule)
		}
		doc.Revision++
		return nil
	})
}
